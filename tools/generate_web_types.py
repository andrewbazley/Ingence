"""Generate the Dashboard's TypeScript declarations from the exported ``/api/v1`` schemas.

The chain is models -> JSON Schema -> declarations: ``tools/export_schemas.py`` writes one JSON
Schema per ``/api/v1`` response model under ``schemas/api/v1/``, and this reads those files --
never the engine -- and writes ``src/ingence/web/types/api.d.ts``, which the page's JavaScript
imports in its JSDoc and ``tsc`` checks. A page that assumes a field the contract does not hold
fails the type check; a declaration file that lags the schemas fails ``--check``.

Deterministic: interfaces in name order, properties in schema order, one output for one input.
Only the JSON Schema that Pydantic emits for these models is understood (objects, arrays,
``anyOf``, ``$ref`` to ``$defs``, ``const``, ``enum``, maps and the scalars); anything else is
refused by name rather than declared as ``any``.

Run with ``--check`` to verify without writing.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
SCHEMA_DIRECTORY = REPOSITORY_ROOT / "schemas" / "api" / "v1"
OUTPUT = REPOSITORY_ROOT / "src" / "ingence" / "web" / "types" / "api.d.ts"
SUFFIX = ".schema.json"

HEADER = """\
// Generated by tools/generate_web_types.py from schemas/api/v1/*.schema.json. Do not edit:
// change the Pydantic models, run tools/export_schemas.py, then this.
//
// Identifiers are strings, counts are integers a browser holds exactly, and times are ISO 8601
// strings with their zone (api/v1/models.py). A property marked optional (?) has a default the
// server may leave out of the schema's required list; the server always sends it.
"""


class UnsupportedSchemaError(ValueError):
    """A schema construct this generator does not declare."""


def _pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.replace("-", "_").split("_"))


def _literal(value: Any) -> str:
    return json.dumps(value)


def _type(schema: dict[str, Any], where: str) -> str:
    """The TypeScript type of one JSON Schema node."""
    if "$ref" in schema:
        reference = str(schema["$ref"])
        prefix = "#/$defs/"
        if not reference.startswith(prefix):
            message = f"{where}: a reference outside $defs, {reference}"
            raise UnsupportedSchemaError(message)
        return reference[len(prefix) :]
    if "const" in schema:
        return _literal(schema["const"])
    if "enum" in schema:
        return " | ".join(_literal(value) for value in schema["enum"])
    if "anyOf" in schema:
        members = [_type(member, where) for member in schema["anyOf"]]
        return " | ".join(dict.fromkeys(members))
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        items = schema.get("items")
        if not isinstance(items, dict):
            message = f"{where}: an array without one item schema"
            raise UnsupportedSchemaError(message)
        inner = _type(items, f"{where}[]")
        return f"Array<{inner}>"
    if kind == "object":
        if "properties" in schema:
            message = f"{where}: an inline object with properties; declare it as a model"
            raise UnsupportedSchemaError(message)
        values = schema.get("additionalProperties")
        if isinstance(values, dict):
            return f"{{ [key: string]: {_type(values, f'{where}{{}}')} }}"
        if values is True or values is None:
            return "{ [key: string]: unknown }"
        return "Record<string, never>"
    if not schema:
        return "unknown"
    message = f"{where}: no declaration for {json.dumps(schema, sort_keys=True)}"
    raise UnsupportedSchemaError(message)


def _comment(text: str, indent: str) -> list[str]:
    lines = [line.rstrip() for line in text.strip().splitlines()]
    return [f"{indent}/**", *[f"{indent} * {line}".rstrip() for line in lines], f"{indent} */"]


def _interface(name: str, schema: dict[str, Any]) -> list[str]:
    if schema.get("type") != "object" or "properties" not in schema:
        # A named type that is not a model: Pydantic's JsonValue ({}, any JSON), or an alias.
        return [
            *(_comment(str(schema["description"]), "") if schema.get("description") else []),
            f"export type {name} = {_type(schema, name)};",
        ]
    lines: list[str] = []
    if schema.get("description"):
        lines += _comment(str(schema["description"]), "")
    lines.append(f"export interface {name} {{")
    required = set(schema.get("required", ()))
    for field, node in schema["properties"].items():
        if node.get("description"):
            lines += _comment(str(node["description"]), "  ")
        optional = "" if field in required else "?"
        lines.append(f"  {field}{optional}: {_type(node, f'{name}.{field}')};")
    lines.append("}")
    return lines


def declarations(directory: Path = SCHEMA_DIRECTORY) -> str:
    """Return the declaration file for every schema under ``directory``."""
    interfaces: dict[str, dict[str, Any]] = {}
    responses: dict[str, str] = {}
    for path in sorted(directory.glob(f"*{SUFFIX}")):
        schema = json.loads(path.read_text(encoding="utf-8"))
        registered = path.name[: -len(SUFFIX)]
        for name, definition in sorted(schema.get("$defs", {}).items()):
            if name in interfaces and interfaces[name] != definition:
                message = f"two schemas define {name} differently; give one model another name"
                raise UnsupportedSchemaError(message)
            interfaces[name] = definition
        top = {key: value for key, value in schema.items() if key != "$defs"}
        title = str(top.get("title") or _pascal(registered))
        if title in interfaces and interfaces[title] != top:
            message = f"two schemas define {title} differently; give one model another name"
            raise UnsupportedSchemaError(message)
        interfaces[title] = top
        responses[registered] = title
    lines = [HEADER.rstrip("\n"), ""]
    for name in sorted(interfaces):
        lines += _interface(name, interfaces[name])
        lines.append("")
    lines += _comment(
        "Every /api/v1 response model, by the name its exported schema is registered under.", ""
    )
    lines.append("export interface ApiResponses {")
    lines += [f"  {registered}: {title};" for registered, title in sorted(responses.items())]
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    """Write or verify the declaration file."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the checked-in declarations match the schemas, without writing",
    )
    args = parser.parse_args(argv[1:])
    expected = declarations()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else None
        if current != expected:
            print(f"out of date: {OUTPUT.relative_to(REPOSITORY_ROOT)}", file=sys.stderr)
            print("\nRegenerate with: python tools/generate_web_types.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(REPOSITORY_ROOT)} is current")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPOSITORY_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
